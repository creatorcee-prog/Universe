function rasterPolys(data, W, H, polys, value, channel) {
  // Even-odd scanline fill in an equirectangular grid (x = longitude, y = latitude from north).
  for (const poly of polys) {
    const n = poly.length;
    for (let y = 0; y < H; y++) {
      const lat = 90 - ((y + 0.5) / H) * 180;
      const xs = [];
      for (let i = 0; i < n; i++) {
        const [x1, y1] = poly[i], [x2, y2] = poly[(i + 1) % n];
        if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
      }
      xs.sort((a, b) => a - b);
      for (let k = 0; k + 1 < xs.length; k += 2) {
        const x0 = Math.max(0, Math.floor(((xs[k] + 180) / 360) * W)), x1 = Math.min(W - 1, Math.floor(((xs[k + 1] + 180) / 360) * W));
        for (let x = x0; x <= x1; x++) data[(y * W + x) * 4 + channel] = value;
      }
    }
  }
}

function blurChannel(data, W, H, ch, r) {
  const tmp = new Float32Array(W * H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let s = 0, n = 0;
    for (let k = -r; k <= r; k++) { s += data[(y * W + ((x + k + W) % W)) * 4 + ch]; n++; }
    tmp[y * W + x] = s / n;
  }
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let s = 0, n = 0;
    for (let k = -r; k <= r; k++) { const yy = Math.min(H - 1, Math.max(0, y + k)); s += tmp[yy * W + x]; n++; }
    data[(y * W + x) * 4 + ch] = s / n;
  }
}

function stampRanges(data, W, H, ranges, ch) {
  for (const [line, hw, height] of ranges) {
    for (let y = 0; y < H; y++) {
      const lat = 90 - ((y + 0.5) / H) * 180;
      for (let x = 0; x < W; x++) {
        const lon = ((x + 0.5) / W) * 360 - 180;
        let best = Infinity;
        for (let i = 0; i + 1 < line.length; i++) {
          const [ax, ay] = line[i], [bx, by] = line[i + 1];
          const cl = Math.cos((lat * Math.PI) / 180);
          const px = (lon - ax) * cl, py = lat - ay, vx = (bx - ax) * cl, vy = by - ay;
          const t = Math.max(0, Math.min(1, (px * vx + py * vy) / (vx * vx + vy * vy || 1)));
          const dx = px - vx * t, dy = py - vy * t;
          best = Math.min(best, dx * dx + dy * dy);
        }
        const d = Math.sqrt(best);
        if (d < hw * 1.6) {
          const v = height * Math.exp(-(d * d) / (hw * hw)) * 255;
          const o = (y * W + x) * 4 + ch;
          data[o] = Math.max(data[o], v);
        }
      }
    }
  }
}

// Earth: R = land (blurred, so 0.5 is the coastline), G = mountains, B = ice sheets, A = 255 (use this map).
export function earthMap(W = 512, H = 256) {
  const d = new Uint8ClampedArray(W * H * 4);
  rasterPolys(d, W, H, LAND, 255, 0);
  rasterPolys(d, W, H, SEAS, 0, 0);
  blurChannel(d, W, H, 0, 2);
  stampRanges(d, W, H, RANGES, 1);
  // Ice sheets where the ranges mark Greenland's and Antarctica's domes.
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const o = (y * W + x) * 4, lat = 90 - ((y + 0.5) / H) * 180, lon = ((x + 0.5) / W) * 360 - 180;
    const greenland = lon > -73 && lon < -12 && lat > 60 && lat < 84 && d[o] > 128;
    if (greenland || lat < -62) d[o + 2] = d[o] > 100 ? 255 : 0;
    d[o + 3] = 255;
  }
  return new Uint8Array(d.buffer);
}

// Moon: R = mare (dark basalt), G unused, B = bright ray systems (Tycho, Copernicus), A = 255.
