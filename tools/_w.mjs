import { chromium, devices } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage(); const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text().slice(0, 300)); });
await page.goto('http://localhost:8080/');
await page.waitForTimeout(3000);
await page.evaluate(async () => {
  const B = await import('./js/bodies.js');
  app.loadPreset('empty');
  const s = app.world.bodies.find((x) => x.kind === 'star');
  const b = B.makeBody({ ...B.CATALOG.find((c) => c.id === 'earth'), name: 'Terra', compKey: 'Earth' });
  b.x = s.x + 1; b.y = s.y; b.z = s.z; b.vz = 6.28; b.life = true; app.world.addBody(b);
  setInterval(() => { if (b.th) b.th.cloud = 0.95; }, 5);
  app.ui.setSpeed(1 / 3650); window.__b = b;
});
await page.waitForTimeout(4000);
await page.evaluate(() => { app.ui.setSpeed(0); app.enterSurface(window.__b, 'day'); });
await page.waitForTimeout(6000);
console.log(await page.evaluate(() => JSON.stringify({ w: app.r3d.weather, clouds: app.r3d.cloudsNow, err: app.r3d.gl.getError() })), errs.slice(0, 5));
await browser.close();
