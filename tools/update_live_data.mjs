// Refreshes js/livedata.js, the real-world data built into the app (so even the offline artifact starts right):
//  - CelesTrak GP orbital elements (celestrak.org, public): the craft in presets.js CRAFT and GEO by NORAD number,
//    and every operational GPS satellite (group gps-ops);
//  - JPL Horizons state vectors (ssd.jpl.nasa.gov, public) of the deep-space probes, heliocentric ecliptic J2000.
// The Pages copy also fetches fresh elements at startup (js/live.js); Horizons sends no CORS header, so the probes
// are refreshed only here. Usage: node tools/update_live_data.mjs
import { writeFileSync } from 'fs';
import { execFileSync } from 'child_process';

const CATNR = { 'ISS': 25544, 'Tiangong': 48274, 'Hubble Space Telescope': 20580, 'Terra': 25994, 'Landsat 8': 39084, 'Landsat 9': 49260,
  'Chandra X-ray Observatory': 25867, 'Vanguard 1': 5, 'GOES-19 (GOES-East)': 60133, 'GOES-18 (GOES-West)': 51850, 'Meteosat-10': 38552,
  'Himawari-9': 41836, 'Intelsat 37e': 42950, 'Fengyun-4B': 48808 };
const PROBES = { 'Voyager 1': -31, 'Voyager 2': -32, 'New Horizons': -98, 'Pioneer 10': -23, 'Pioneer 11': -24, 'Parker Solar Probe': -96 };
const pick = (g) => ({ name: g.OBJECT_NAME, id: g.NORAD_CAT_ID, epoch: g.EPOCH, n: g.MEAN_MOTION, e: g.ECCENTRICITY, i: g.INCLINATION, raan: g.RA_OF_ASC_NODE, w: g.ARG_OF_PERICENTER, M: g.MEAN_ANOMALY });
// (curl, which follows the machine's proxy settings; Node's fetch does not)
const get = async (u) => {
  for (let k = 0; ; k++) {
    try { const t = execFileSync('curl', ['-sS', '--fail', '--max-time', '60', u], { maxBuffer: 1 << 26 }).toString(); return { json: async () => JSON.parse(t) }; }
    catch (e) { if (k >= 3) throw e; await new Promise((ok) => setTimeout(ok, 4000 * (k + 1))); }   // (CelesTrak resets bursts: wait and retry)
  }
};

const gp = {};
for (const [name, id] of Object.entries(CATNR)) {
  await new Promise((ok) => setTimeout(ok, 1500));   // (gently: CelesTrak limits request rates)
  try { const j = await (await get(`https://celestrak.org/NORAD/elements/gp.php?CATNR=${id}&FORMAT=json`)).json(); if (j[0]) gp[name] = pick(j[0]); else console.warn('no elements', name); }
  catch (e) { console.warn(name, e.message); }
}
let gps = [];
try { gps = (await (await get('https://celestrak.org/NORAD/elements/gp.php?GROUP=gps-ops&FORMAT=json')).json()).map(pick); } catch (e) { console.warn('gps', e.message); }

const now = new Date(), d0 = now.toISOString().slice(0, 10), d1 = new Date(now.getTime() + 86400e3).toISOString().slice(0, 10);
const probes = {};
for (const [name, id] of Object.entries(PROBES)) {
  const q = new URLSearchParams({ format: 'json', COMMAND: `'${id}'`, EPHEM_TYPE: 'VECTORS', CENTER: "'500@10'", START_TIME: `'${d0}'`, STOP_TIME: `'${d1}'`, STEP_SIZE: "'1d'", OUT_UNITS: "'AU-D'", VEC_TABLE: "'2'", REF_PLANE: "'ECLIPTIC'", REF_SYSTEM: "'J2000'", CSV_FORMAT: "'YES'" });
  try {
    const j = await (await get('https://ssd.jpl.nasa.gov/api/horizons.api?' + q)).json();
    const block = j.result.split('$$SOE')[1].split('$$EOE')[0].trim().split('\n')[0].split(',').map((s) => s.trim());
    // JDTDB, date, X, Y, Z, VX, VY, VZ
    probes[name] = { jd: +block[0], x: +block[2], y: +block[3], z: +block[4], vx: +block[5], vy: +block[6], vz: +block[7] };
  } catch (e) { console.warn(name, e.message); }
}
const out = `// Generated by tools/update_live_data.mjs on ${now.toISOString()} (CelesTrak GP elements; JPL Horizons vectors: AU, AU/day,\n// heliocentric ecliptic J2000). js/live.js replaces the elements with fresh ones when it can reach CelesTrak.\nexport const LIVE_DATA = ${JSON.stringify({ fetched: now.toISOString(), gp, gps, probes })};\n`;
writeFileSync(new URL('../js/livedata.js', import.meta.url), out);
console.log('craft', Object.keys(gp).length, 'gps', gps.length, 'probes', Object.keys(probes).length, Math.round(out.length / 1024), 'KB');
