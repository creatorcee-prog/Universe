// Builds js/wgsl.js: every WebGL program of the Realistic view translated to WGSL, for the WebGPU
// renderer (js/glgpu.js runs render3d.js's WebGL calls on WebGPU). Run after changing js/shaders.js:
//   node tools/make_wgsl.mjs        (needs a local server on :8080 serving the repo, and Playwright)
// GLSL ES -> Vulkan GLSL (tools/glsl2vk.mjs) -> SPIR-V (glslang) -> WGSL (Tint), the last two in headless
// Chromium (tools/vendor/translate.html).
import { writeFileSync } from 'fs';
import { chromium } from 'playwright';
import { convert, std140, programKey } from './glsl2vk.mjs';

import { PROGRAMS } from './wgsl-programs.mjs';

// The vendored Tint is older than today's WGSL: array strides were an attribute, and derivatives were
// allowed anywhere. Arrays of vec4 already have a 16-byte stride; arrays of f32 with a 16-byte stride become
// arrays of a padded struct (and their reads take .el). GLSL never required derivatives in uniform control
// flow, and the shaders rely on that, so that check is switched off.
function modernize(w) {
  const padded = [];
  w = w.replace(/alias (\w+) = @stride\(16\) array<vec4<f32>, (\d+)u>;/g, 'alias $1 = array<vec4<f32>, $2u>;');
  w = w.replace(/alias (\w+) = @stride\(16\) array<f32, (\d+)u>;/g, (all, name, n) => { padded.push(name); return `alias ${name} = array<GPUPadF32, ${n}u>;`; });
  if (/@stride/.test(w)) throw new Error('unhandled @stride: ' + w.match(/.*@stride.*/)[0]);
  if (padded.length) {
    w = 'struct GPUPadF32 {\n  @size(16)\n  el : f32,\n}\n\n' + w;
    // Members of the uniform struct with a padded type: x.member[i] reads become x.member[i].el.
    const members = [];
    for (const m of w.matchAll(/\n\s*(\w+) : (\w+),/g)) if (padded.includes(m[2])) members.push(m[1]);
    for (const mem of members) w = w.replace(new RegExp(`\\.${mem}\\[([^\\[\\]]*(?:\\[[^\\]]*\\][^\\[\\]]*)*)\\]`, 'g'), `.${mem}[$1].el`);
  }
  return 'diagnostic(off, derivative_uniformity);\n' + w;
}

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('http://localhost:8080/tools/vendor/translate.html');
await page.waitForFunction(() => window.ready, null, { timeout: 60000 });
const out = {};
let failed = 0;
for (const [name, vsSrc, fsSrc, points] of PROGRAMS) {
  let c;
  try { c = convert(vsSrc, fsSrc, { points: !!points }); } catch (e) { console.log(name, 'CONVERT', e.message); failed++; continue; }
  const r = {};
  for (const [st, src] of [['vertex', c.vs], ['fragment', c.fs]]) {
    const res = await page.evaluate(([s, t]) => window.toWGSL(s, t), [src, st]);
    if (res.error) {
      const log = await page.evaluate(() => (window.lastLog || ''));
      console.log(name, st, 'TRANSLATE', res.error, log);
      writeFileSync(`/tmp/wgsl-fail-${name}-${st}.glsl`, src);
      failed++;
    }
    r[st] = res.wgsl;
  }
  if (!r.vertex || !r.fragment) continue;
  r.vertex = modernize(r.vertex); r.fragment = modernize(r.fragment);
  const lay = std140(c.uniforms);
  // Cross-check the layout with the offsets Tint reports in the struct it emits.
  for (const w of [r.vertex, r.fragment]) {
    const sm = w.match(/struct GPUU \{([\s\S]*?)\n\}/);
    if (!sm) continue;
    for (const mm of sm[1].matchAll(/@offset\((\d+)\) \*\/\s*(\w+)\s*:/g)) {
      const mem = lay.members.find((x) => x.name === mm[2]);
      if (mem && mem.offset !== +mm[1]) { console.log(name, 'OFFSET MISMATCH', mm[2], mem.offset, mm[1]); failed++; }
    }
  }
  out[programKey(vsSrc, fsSrc)] = { name, vs: r.vertex, fs: r.fragment, points: !!points, size: lay.size, uniforms: lay.members, samplers: c.samplers, attributes: c.attributes };
  console.log(name.padEnd(8), 'ok', lay.size, 'bytes of uniforms,', c.samplers.length, 'textures');
}
await browser.close();
writeFileSync('js/wgsl.js', '// Generated by tools/make_wgsl.mjs from js/shaders.js: do not edit.\nexport const WGSL = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'programs written,', failed, 'problems');
process.exit(failed ? 1 : 0);
